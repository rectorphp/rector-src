<?php

declare(strict_types=1);

use Rector\Config\RectorConfig;
use Rector\Configuration\Option;
use Rector\Configuration\Parameter\SimpleParameterProvider;
use Rector\Doctrine\Set\DoctrineSetList;
use Rector\PHPUnit\Set\PHPUnitSetList;
use Rector\Symfony\Set\SymfonySetList;
use Rector\Symfony\Set\TwigSetList;
use Rector\VersionBonding\Contract\ComposerPackageConstraintInterface;
use Rector\VersionBonding\ValueObject\ComposerBoundRuleConfiguration;
use Symfony\Component\Console\Input\ArrayInput;
use Symfony\Component\Console\Output\ConsoleOutput;
use Symfony\Component\Console\Style\SymfonyStyle;

require __DIR__ . '/../vendor/autoload.php';

// regenerates src/Configuration/ComposerBasedTriggerPackages.php from the packages the composer-based sets are bound to
$composerBasedSetFiles = [
    'twig' => TwigSetList::COMPOSER_BASED,
    'doctrine' => DoctrineSetList::COMPOSER_BASED,
    'phpunit' => PHPUnitSetList::COMPOSER_BASED,
    'symfony' => SymfonySetList::COMPOSER_BASED,
];

// rector-laravel and drupal-rector are not required here, so their sets cannot be read
$extensionTriggerPackages = [
    'laravel' => ['laravel/framework', 'illuminate/support'],
    'drupal' => ['drupal/core'],
];

$triggerPackages = [];

foreach ($composerBasedSetFiles as $argumentName => $composerBasedSetFile) {
    // the parameter provider is static, start each set from scratch
    SimpleParameterProvider::setParameter(Option::COMPOSER_BOUND_RULE_CONFIGURATIONS, []);

    $rectorConfig = new RectorConfig();

    /** @var callable $configCallable */
    $configCallable = require $composerBasedSetFile;
    $configCallable($rectorConfig);

    $rectorClasses = array_merge(
        $rectorConfig->getMainRectorClasses(),
        array_keys($rectorConfig->getRuleConfigurations())
    );

    $packageNames = [];

    foreach (array_unique($rectorClasses) as $rectorClass) {
        // the package constraint does not depend on constructor dependencies, skip them
        $rector = new ReflectionClass($rectorClass)->newInstanceWithoutConstructor();
        if (! $rector instanceof ComposerPackageConstraintInterface) {
            continue;
        }

        $composerPackageConstraint = $rector->provideComposerPackageConstraint();
        $composerPackageConstraints = is_array($composerPackageConstraint)
            ? $composerPackageConstraint
            : [$composerPackageConstraint];

        foreach ($composerPackageConstraints as $composerPackageConstraint) {
            $packageNames[] = $composerPackageConstraint->getPackageName();
        }
    }

    // rule configurations registered via ruleWithConfigurationComposerVersionBound(), the inactive ones included
    $composerBoundRuleConfigurations = SimpleParameterProvider::provideArrayParameter(
        Option::COMPOSER_BOUND_RULE_CONFIGURATIONS
    );

    foreach ($composerBoundRuleConfigurations as $composerBoundRuleConfiguration) {
        if ($composerBoundRuleConfiguration instanceof ComposerBoundRuleConfiguration) {
            $packageNames[] = $composerBoundRuleConfiguration->getPackageName();
        }
    }

    $packageNames = array_values(array_unique($packageNames));
    sort($packageNames);

    $triggerPackages[$argumentName] = $packageNames;
}

$triggerPackages = array_merge($triggerPackages, $extensionTriggerPackages);

$printedTriggerPackages = '';
foreach ($triggerPackages as $argumentName => $packageNames) {
    $printedTriggerPackages .= sprintf("        '%s' => [\n", $argumentName);

    foreach ($packageNames as $packageName) {
        $printedTriggerPackages .= sprintf("            '%s',\n", $packageName);
    }

    $printedTriggerPackages .= "        ],\n";
}

$fileContents = <<<PHP
<?php

declare(strict_types=1);

namespace Rector\Configuration;

/**
 * Generated by "php scripts/generate-composer-based-trigger-packages.php", do not edit manually
 */
final class ComposerBasedTriggerPackages
{
    /**
     * Any of these installed packages loads the composer-based set of withComposerBased() argument
     *
     * @var array<string, string[]>
     */
    public const array PACKAGES_BY_ARGUMENT = [
{$printedTriggerPackages}    ];
}

PHP;

$targetFilePath = __DIR__ . '/../src/Configuration/ComposerBasedTriggerPackages.php';
file_put_contents($targetFilePath, $fileContents);

$symfonyStyle = new SymfonyStyle(new ArrayInput([]), new ConsoleOutput());

foreach ($triggerPackages as $argumentName => $packageNames) {
    $symfonyStyle->writeln(sprintf('<fg=green>%s</>: %d packages', $argumentName, count($packageNames)));
}

$symfonyStyle->success(sprintf('File "%s" was generated', realpath($targetFilePath)));
